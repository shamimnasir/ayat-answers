// A prime stride visits every verse once before repeating, without consecutive days
// landing on neighbouring verses. The list must stay shorter than the stride.
const STRIDE = 7919;

export function pickDailyVerse(date: Date): readonly [number, number] {
  const day = Math.floor(Date.UTC(date.getFullYear(), date.getMonth(), date.getDate()) / 86_400_000);
  return DAILY_VERSES[(day * STRIDE) % DAILY_VERSES.length];
}
